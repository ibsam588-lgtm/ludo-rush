"""Build Android string resources consumed by Flutter's localized text bridge.

Play Console translates Android string resources in uploaded bundles. Flutter
strings are otherwise invisible to that service, so both platforms share this
catalog of English UI copy. Run this after adding or changing UI text.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
from xml.sax.saxutils import escape


ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE_ROOT = ROOT / "lib"
SOURCES = [
    *sorted((SOURCE_ROOT / "screens").rglob("*.dart")),
    *sorted((SOURCE_ROOT / "widgets").rglob("*.dart")),
    SOURCE_ROOT / "state" / "app_state.dart",
    SOURCE_ROOT / "data" / "profile_catalog.dart",
    SOURCE_ROOT / "data" / "table_reactions.dart",
]
LITERAL = re.compile(r"(?<![A-Za-z0-9])(['\"])((?:\\.|(?!\1).)*?)\1", re.S)


def is_ui_text(value: str) -> bool:
    if value in {"Ludo Rush", "LUDO RUSH"} or value.endswith(" USD"):
        return False
    if not 2 <= len(value) <= 180 or "\n" in value or "$" in value or "\\" in value:
        return False
    if not re.search(r"[A-Za-z]", value):
        return False
    if "/" in value or "http" in value or "_" in value or value.count(".") > 1:
        return False
    if " " not in value and (
        value[0].islower() or len(value) > 28 or (value.isupper() and len(value) <= 3)
    ):
        return False
    return re.fullmatch(r"[A-Za-z0-9]{15,}", value) is None


def android_value(value: str) -> str:
    # AAPT treats apostrophes, quotes and leading @/? as syntax.
    escaped = value.replace('"', r'\"').replace("'", r"\'")
    if escaped.startswith(("@", "?")):
        escaped = "\\" + escaped
    return escape(escaped)


def main() -> None:
    phrases = set()
    for source in SOURCES:
        for _, value in LITERAL.findall(source.read_text(encoding="utf-8")):
            if is_ui_text(value):
                phrases.add(value)

    keys = {
        phrase: "ludo_ui_" + hashlib.sha1(phrase.encode("utf-8")).hexdigest()[:12]
        for phrase in sorted(phrases)
    }
    resources = ROOT / "android/app/src/main/res/values/ludo_ui_strings.xml"
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<resources>",
        '    <string name="app_name" translatable="false">Ludo Rush</string>',
    ]
    for phrase, key in keys.items():
        lines.append(
            f'    <string name="{key}" formatted="false">{android_value(phrase)}</string>'
        )
    lines.append('    <string-array name="ludo_ui_string_keys" translatable="false">')
    for key in keys.values():
        lines.append(f"        <item>{key}</item>")
    lines.append("    </string-array>")
    # Explicit references keep these resources in minified release bundles.
    lines.append('    <string-array name="ludo_ui_string_values" translatable="false">')
    for key in keys.values():
        lines.append(f"        <item>@string/{key}</item>")
    lines.extend(["    </string-array>", "</resources>", ""])
    resources.write_text("\n".join(lines), encoding="utf-8")

    dart = SOURCE_ROOT / "l10n/ludo_string_keys.dart"
    dart.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tool/generate_play_strings.py. Do not edit by hand.",
        "const Map<String, String> ludoStringKeys = {",
    ]
    for phrase, key in keys.items():
        literal = json.dumps(phrase, ensure_ascii=False).replace("$", r"\$")
        lines.append(f"  {literal}: '{key}',")
    lines.extend(["};", ""])
    dart.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(keys)} translatable UI strings")


if __name__ == "__main__":
    main()
