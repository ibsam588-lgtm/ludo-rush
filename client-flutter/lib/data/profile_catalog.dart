CountrySpec countryByCode(String code) {
  final normalized = code.trim().toUpperCase();
  return allCountries.firstWhere(
    (country) => country.code == normalized,
    orElse: () => const CountrySpec('US', 'United States'),
  );
}

String countryFlagEmoji(String code) {
  final normalized = code.trim().toUpperCase();
  if (normalized.length != 2) return '';
  const regionalIndicatorA = 0x1F1E6;
  return String.fromCharCodes([
    regionalIndicatorA + normalized.codeUnitAt(0) - 65,
    regionalIndicatorA + normalized.codeUnitAt(1) - 65,
  ]);
}
